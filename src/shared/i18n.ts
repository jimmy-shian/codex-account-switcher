/** 長詞優先，避免「資料」被拆成單字再誤替換 */
const PHRASE_KEYS = Object.keys(PHRASES).sort((a, b) => b.length - a.length)
const CHAR_KEYS = Object.keys(CHARS)

/**
 * 把簡體中文轉成繁體（台灣用語）。
 * 輸入已是繁體時不會改動，因此可以重複呼叫。
 */
export function toTraditional(text: string): string {
  if (!text) return text
  let out = text
  for (const key of PHRASE_KEYS) {
    if (out.includes(key)) out = out.split(key).join(PHRASES[key])
  }
  for (const key of CHAR_KEYS) {
    if (out.includes(key)) out = out.split(key).join(CHARS[key])
  }
  return out
}

/** 依語言設定輸出文案；zh-CN 直接回傳原文 */
export function localize(text: string, locale: UiLocale): string {
  return locale === 'zh-TW' ? toTraditional(text) : text
}